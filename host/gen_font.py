#!/usr/bin/env python3
"""Generate src/pde_font.{h,cpp}: the default font's outlines plus the constant tables the C++
drawing runtime must share bit for bit with the reference interpreter (noise cosine table, SIN, BLUE16).

    python3 host/gen_font.py [output directory, default src/]

The source of truth is the Python package (python/immanence/pde/font_data.py, jrandom.py,
textures.py, ../tables.py); never edit the generated files by hand.
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "src")
sys.path.insert(0, os.path.join(HERE, "..", "python"))

from immanence.pde import font_data  # noqa: E402
from immanence.pde.jrandom import Randomness  # noqa: E402
from immanence.pde.textures import BLUE16  # noqa: E402
from immanence.tables import SIN  # noqa: E402

codes = sorted(font_data.GLYPHS)
coords, contours, glyphs = [], [], []
for code in codes:
    adv, cs = font_data.GLYPHS[code]
    assert adv == int(adv) and 0 <= adv < 32768
    first = len(contours)
    for c in cs:
        assert len(c) % 2 == 0
        contours.append((len(coords) // 2, len(c) // 2))
        coords.extend(c)
    glyphs.append((code, int(adv), first, len(cs)))
assert all(-32768 <= v < 32768 for v in coords)
assert len(coords) // 2 < 65536 and len(contours) < 65536
fsc = Randomness().fsc
assert len(fsc) == 720


def f32lit(v):
    """A float32 literal that round-trips exactly (hex; the value is already float32)."""
    assert struct.unpack("<f", struct.pack("<f", v))[0] == v
    return f"{v.hex()}f"


def rows(vals, per=16):
    vals = list(vals)
    return ",\n".join("  " + ", ".join(vals[i:i + per]) for i in range(0, len(vals), per))


h = f"""// GENERATED by gen_font.py from the reference interpreter in python/immanence/pde -- do not edit.
#pragma once
#include <cstdint>

namespace pde {{
namespace font {{
constexpr int ASCENT = {font_data.ASCENT};
constexpr int DESCENT = {font_data.DESCENT};
struct Glyph {{ uint16_t code; int16_t advance; uint16_t first_contour, n_contours; }};
struct Contour {{ uint16_t first_point, n_points; }};
constexpr int N_GLYPHS = {len(glyphs)};
extern const Glyph GLYPHS[N_GLYPHS];        // sorted by code
extern const Contour CONTOURS[{len(contours)}];
extern const int16_t POINTS[{len(coords)}];  // x, y pairs in 1/1000 em, y down
// the glyph of a UTF-16 code unit, or nullptr (font_data.GLYPHS.get(code))
const Glyph *find(uint32_t code);
}}  // namespace font

// PApplet.noise_fsc per index: f32(0.5 * f32(1 - cos[i])), computed by the reference's jrandom.py
extern const float NOISE_FSC[720];
extern const int16_t SIN1024[360];     // python/immanence/tables.py SIN
extern const uint8_t BLUE16[256];      // textures.py BLUE16
}}  // namespace pde
"""

cpp = f"""#include "pde_fp.h"  // first: no fused multiply-add (see the header)
// GENERATED by gen_font.py from the reference interpreter in python/immanence/pde -- do not edit.
// Font: Processing Sans Pro (Adobe Source Sans), SIL Open Font License 1.1.
#include "pde_font.h"

namespace pde {{
namespace font {{
const Glyph GLYPHS[N_GLYPHS] = {{
{rows((f"{{{c}, {a}, {f}, {n}}}" for c, a, f, n in glyphs), 6)}
}};
const Contour CONTOURS[{len(contours)}] = {{
{rows((f"{{{a}, {b}}}" for a, b in contours), 8)}
}};
const int16_t POINTS[{len(coords)}] = {{
{rows((str(v) for v in coords), 16)}
}};
const Glyph *find(uint32_t code) {{
  int lo = 0, hi = N_GLYPHS;
  while (lo < hi) {{
    int m = (lo + hi) >> 1;
    if (GLYPHS[m].code < code) lo = m + 1; else hi = m;
  }}
  return lo < N_GLYPHS && GLYPHS[lo].code == code ? &GLYPHS[lo] : nullptr;
}}
}}  // namespace font

const float NOISE_FSC[720] = {{
{rows((f32lit(v) for v in fsc), 6)}
}};
const int16_t SIN1024[360] = {{
{rows((str(v) for v in SIN), 20)}
}};
const uint8_t BLUE16[256] = {{
{rows((str(v) for v in BLUE16), 16)}
}};
}}  // namespace pde
"""
with open(os.path.join(OUT, "pde_font.h"), "w") as f:
    f.write(h)
with open(os.path.join(OUT, "pde_font.cpp"), "w") as f:
    f.write(cpp)
print(f"{len(glyphs)} glyphs, {len(contours)} contours, {len(coords) // 2} points")
