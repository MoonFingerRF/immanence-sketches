"""The `immanence` command.

    immanence compile piece.pde [-o piece.pdeb]       Processing source -> VM bytecode
    immanence compile piece.pde --c NAME [-o piece.h] the same as a C header with golden frame hashes
    immanence check piece.pde [--frames 60] [--json] [--png preview.png]
                                                      compiles, runs, is it a picture? (exit 0 = yes)
    immanence run piece.pde [--frames N] [--png out.png | --sheet sheet.png] [--pgm-dir DIR]
                                                      run on the reference interpreter, save frames
    immanence info piece.pdeb                         what a bytecode file holds
    immanence fetch <id|list> [-o DIR] [--site URL]   a piece from the immanencepure.xyz API
    immanence reference [language|library]            the references a model writes from
"""
from __future__ import annotations

import argparse
import json
import os
import struct
import sys
import urllib.request
import zlib

from . import (BYTECODE_VERSION, MAGIC, H, PdeError, Unsupported, W, check, compile_pde, find_vm,
               for_compiler, render, run_native)

SITE = "https://immanencepure.xyz"
HERE = os.path.dirname(os.path.abspath(__file__))


# ---------------------------------------------------------------- images (no dependencies)
def png_grey(path: str, w: int, h: int, pixels: bytes, scale: int = 1) -> None:
    """Write an 8-bit greyscale PNG, optionally scaled up by an integer factor (nearest neighbour)."""
    if scale > 1:
        rows = []
        for y in range(h):
            row = bytes(b for b in pixels[y * w:(y + 1) * w] for _ in range(scale))
            rows.extend([row] * scale)
        w, h, raw = w * scale, h * scale, b"".join(b"\x00" + r for r in rows)
    else:
        raw = b"".join(b"\x00" + pixels[y * w:(y + 1) * w] for y in range(h))

    def chunk(tag: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data))

    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 0, 0, 0, 0))
                + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def contact_sheet(frames: list[bytes], cols: int = 4, gap: int = 4, bg: int = 128) -> tuple[int, int, bytes]:
    """Frames side by side (row-major), `gap` pixels of mid grey between them."""
    n = len(frames)
    rows = (n + cols - 1) // cols
    cols = min(cols, n)
    sw, sh = cols * W + (cols - 1) * gap, rows * H + (rows - 1) * gap
    out = bytearray([bg]) * (sw * sh)
    for k, g in enumerate(frames):
        ox, oy = (k % cols) * (W + gap), (k // cols) * (H + gap)
        for y in range(H):
            out[(oy + y) * sw + ox:(oy + y) * sw + ox + W] = g[y * W:(y + 1) * W]
    return sw, sh, bytes(out)


def pick(frames: list[bytes], n: int) -> list[bytes]:
    if len(frames) <= n:
        return frames
    return [frames[round(i * (len(frames) - 1) / (n - 1))] for i in range(n)]


# ---------------------------------------------------------------- commands
def _read(path: str) -> str:
    if path == "-":
        return sys.stdin.read()
    with open(path, encoding="utf-8") as f:
        return f.read()


def cmd_compile(a) -> int:
    src = _read(a.file)
    try:
        prog = compile_pde(src)
    except PdeError as e:
        print(f"{a.file}:{e.line}: {e.kind}: {e.message}" if e.line else f"{a.file}: {e}", file=sys.stderr)
        return 1
    except Unsupported as e:
        print(f"{a.file}:{e.line}: unsupported: {e.what} (valid Processing, but the VM does not run it)",
              file=sys.stderr)
        return 1
    if a.c:
        return _write_c(a, src, prog)
    out = a.output or (os.path.splitext(a.file)[0] + ".pdeb" if a.file != "-" else "-")
    if out == "-":
        sys.stdout.buffer.write(prog)
    else:
        with open(out, "wb") as f:
            f.write(prog)
        print(f"{out}: {len(prog)} bytes, bytecode v{prog[4]}", file=sys.stderr)
    return 0


def _write_c(a, src: str, prog: bytes) -> int:
    """A C/C++ header with the program and its golden frame hashes, to embed in firmware."""
    from .golden import build
    name = a.c
    g = build(src, k=a.golden) if a.golden > 0 else {"ok": False}
    hashes = g["hashes"] if g.get("ok") and not g.get("clock") else []
    lines = [f"// Generated by `immanence compile --c {name}` from {os.path.basename(a.file)}: do not edit.",
             f"// Bytecode v{prog[4]}, {len(prog)} bytes. {name}_golden: crc32 of the first frames' 240x128 grey",
             "// canvas as the reference draws them (empty for a sketch that reads the clock).",
             "#pragma once", "#include <stddef.h>", "#include <stdint.h>",
             f"static const uint8_t {name}[] = {{"]
    for i in range(0, len(prog), 16):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in prog[i:i + 16]) + ",")
    lines.append("};")
    lines.append(f"static const size_t {name}_len = {len(prog)};")
    body = ", ".join(f"0x{h:08x}u" for h in hashes) or "0"
    lines.append(f"static const uint32_t {name}_golden[] = {{{body}}};")
    lines.append(f"static const int {name}_golden_n = {len(hashes)};")
    text = "\n".join(lines) + "\n"
    out = a.output or (os.path.splitext(a.file)[0] + ".h")
    if out == "-":
        sys.stdout.write(text)
    else:
        with open(out, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"{out}: {name}, {len(prog)} bytes, {len(hashes)} golden frames", file=sys.stderr)
    return 0


def _explain(r: dict, path: str) -> str:
    e = r["error"]
    if r["ok"]:
        kind = "still" if r["still"] else ("animated" if r["animated"] else "unchanging")
        return (f"OK {path}: compiles ({r['bytecode_bytes']} bytes), {r['frames']} frame(s), {kind}, "
                f"ink {r['ink'][0]:.0%}..{r['ink'][1]:.0%}, max {r['max_steps']} steps/frame")
    where = f" line {e['line']}" if isinstance(e, dict) and e.get("line") else ""
    kind = e.get("kind") if isinstance(e, dict) else "error"
    msg = e.get("message") if isinstance(e, dict) else str(e)
    hint = {
        "compile": "fix the code at that line",
        "syntax": "fix the code at that line",
        "unsupported": "use something the VM runs instead (see the language reference)",
        "picture": "draw more (or less): every frame must show something, not an empty or solid canvas",
        "budget": "do less work per frame (smaller loops, fewer pixels)",
        "deadline": "do less work per frame",
        "memory": "allocate less (no new arrays or objects inside draw)",
        "depth": "less recursion or nesting",
        "size": "use size(240, 128)",
        "runtime": "fix the failing line (index out of range, null, division by zero...)",
    }.get(kind, "")
    return f"FAIL {path} at {r['stage']}: {kind}{where}: {msg}" + (f"\n  hint: {hint}" if hint else "")


def cmd_check(a) -> int:
    src = _read(a.file)
    vm = a.vm or find_vm()
    r = check(src, frames=a.frames, vm=vm)
    if (a.png or a.sheet) and r["frames"]:
        rr = run_native(vm, compile_pde(src), a.frames) if vm else render(for_compiler(src), a.frames)
        if rr["frames"]:
            if a.png:
                png_grey(a.png, W, H, rr["frames"][-1], a.scale)
            if a.sheet:
                sw, sh, px = contact_sheet(pick(rr["frames"], 8))
                png_grey(a.sheet, sw, sh, px, a.scale)
    if a.json:
        print(json.dumps({k: v for k, v in r.items() if k != "frame_crc32" or a.crc}, indent=None))
    else:
        print(_explain(r, a.file))
    return 0 if r["ok"] else 1


def cmd_run(a) -> int:
    src = _read(a.file)
    r = render(for_compiler(src), a.frames)
    for i, g in enumerate(r["frames"]):
        print(f"F {i + 1} {zlib.crc32(g):08x} {r['steps'][i]}")
    if r["error"]:
        e = r["error"]
        print(f"END fault {e['kind']} {e['message']}" + (f" (line {e['line']})" if e.get("line") else ""))
    else:
        print("END done" if r["still"] else "END running")
    if r["frames"]:
        if a.png:
            png_grey(a.png, W, H, r["frames"][-1], a.scale)
        if a.sheet:
            sw, sh, px = contact_sheet(pick(r["frames"], a.sheet_frames))
            png_grey(a.sheet, sw, sh, px, a.scale)
        if a.pgm_dir:
            os.makedirs(a.pgm_dir, exist_ok=True)
            for i, g in enumerate(r["frames"]):
                with open(os.path.join(a.pgm_dir, f"frame{i + 1:04d}.pgm"), "wb") as f:
                    f.write(b"P5 %d %d 255\n" % (W, H) + g)
        if a.raw:
            with open(a.raw, "wb") as f:
                for g in r["frames"]:
                    f.write(g)
    return 1 if r["error"] else 0


def cmd_info(a) -> int:
    with open(a.file, "rb") as f:
        b = f.read()
    if b[:4] != MAGIC:
        print(f"{a.file}: not a bytecode file (magic {b[:4]!r})", file=sys.stderr)
        return 1
    info = {"bytes": len(b), "magic": b[:4].decode(), "version": b[4], "supported": b[4] == BYTECODE_VERSION,
            "uses_clock": bool(b[5] & 1), "crc32": "%08x" % zlib.crc32(b)}
    print(json.dumps(info))
    return 0 if info["supported"] else 1


def _get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "immanence-sketches/1"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read()


def cmd_fetch(a) -> int:
    base = a.site.rstrip("/") + "/api/v1"
    if a.id == "list":
        idx = json.loads(_get(base + "/index.json"))
        for p in idx["pieces"]:
            print(f"{p['id']}\t{p['title']}")
        return 0
    info = json.loads(_get(f"{base}/info/{a.id}.json"))
    os.makedirs(a.output, exist_ok=True)
    stem = os.path.join(a.output, a.id)
    with open(stem + ".json", "w", encoding="utf-8") as f:
        json.dump(info, f, indent=1, ensure_ascii=False)
    with open(stem + ".pde", "wb") as f:
        f.write(_get(f"{base}/source/{a.id}.pde"))
    with open(stem + ".pdeb", "wb") as f:
        f.write(_get(f"{base}/bytecode/{a.id}.pdeb"))
    print(f"{stem}.pde, .pdeb, .json: {info['title']}")
    return 0


def cmd_reference(a) -> int:
    name = {"language": "language_reference.md", "library": "library_reference.md"}[a.which]
    with open(os.path.join(HERE, name), encoding="utf-8") as f:
        sys.stdout.write(f.read())
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="immanence", description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("compile", help="Processing source -> bytecode")
    p.add_argument("file")
    p.add_argument("-o", "--output")
    p.add_argument("--c", metavar="NAME", help="write a C header (program + golden frame hashes) instead")
    p.add_argument("--golden", type=int, default=30, help="golden frames for --c (0: none)")
    p.set_defaults(fn=cmd_compile)

    p = sub.add_parser("check", help="compile + run + picture check (exit 0 = passes)")
    p.add_argument("file")
    p.add_argument("--frames", type=int, default=60)
    p.add_argument("--json", action="store_true")
    p.add_argument("--crc", action="store_true", help="include per-frame crc32 in --json")
    p.add_argument("--png", help="save the last frame")
    p.add_argument("--sheet", help="save 8 frames as a contact sheet")
    p.add_argument("--scale", type=int, default=2)
    p.add_argument("--vm", help="native host runner (default: $IMMANENCE_VM or immanence-vm on PATH)")
    p.set_defaults(fn=cmd_check)

    p = sub.add_parser("run", help="run on the reference interpreter")
    p.add_argument("file")
    p.add_argument("--frames", type=int, default=60)
    p.add_argument("--png", help="save the last frame")
    p.add_argument("--sheet", help="save a contact sheet")
    p.add_argument("--sheet-frames", type=int, default=8)
    p.add_argument("--scale", type=int, default=2)
    p.add_argument("--pgm-dir", help="save every frame as PGM")
    p.add_argument("--raw", help="save every frame as raw 240x128 grey bytes, concatenated")
    p.set_defaults(fn=cmd_run)

    p = sub.add_parser("info", help="inspect a .pdeb")
    p.add_argument("file")
    p.set_defaults(fn=cmd_info)

    p = sub.add_parser("fetch", help="download a piece from the site API")
    p.add_argument("id", help="a piece id, or 'list'")
    p.add_argument("-o", "--output", default=".")
    p.add_argument("--site", default=SITE)
    p.set_defaults(fn=cmd_fetch)

    p = sub.add_parser("reference", help="print a reference")
    p.add_argument("which", choices=["language", "library"])
    p.set_defaults(fn=cmd_reference)

    a = ap.parse_args(argv)
    return a.fn(a)


if __name__ == "__main__":
    sys.exit(main())
